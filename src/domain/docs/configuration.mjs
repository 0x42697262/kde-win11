import { CONFIGURATION_EXAMPLE } from "../catalog/settingsSchema.mjs";
import { JSON_INDENT } from "../catalog/units.mjs";

const TABLE_SEPARATOR = " | ";

export const MARKDOWN_HEADER = "<!-- Generated by tools/generate.mjs from src/domain/catalog. Do not edit by hand. -->\n\n";

/** @typedef {import("../settings/definitions.mjs").SettingDefinition} SettingDefinition */

/**
 * @param {unknown} value
 * @returns {string}
 */
function formatDefault(value) {
    return Array.isArray(value) ? value.map((item) => `\`${item}\``).join(", ") || "(empty)" : `\`${JSON.stringify(value)}\``;
}

/**
 * @param {SettingDefinition} definition
 * @returns {string}
 */
function formatAllowed(definition) {
    if (definition.options) {
        return definition.options.map((option) => `\`${option}\``).join(", ");
    }
    if (definition.minimum !== undefined && definition.maximum !== undefined) {
        return `${definition.minimum} to ${definition.maximum}`;
    }
    return "";
}

/**
 * @param {readonly SettingDefinition[]} definitions
 * @param {string} configPath
 * @returns {string}
 */
export function renderConfiguration(definitions, configPath) {
    const sections = [...new Set(definitions.map((definition) => definition.section))];
    const body = sections.map((section) => {
        const rows = definitions.filter((definition) => definition.section === section).map((definition) =>
            `| ${[`\`${definition.key}\``, definition.type, formatDefault(definition.defaultValue), formatAllowed(definition), definition.description].join(TABLE_SEPARATOR)} |`);
        return `## ${section}\n\n| Key | Type | Default | Allowed | Description |\n|---|---|---|---|---|\n${rows.join("\n")}\n`;
    }).join("\n");
    const example = JSON.stringify(CONFIGURATION_EXAMPLE, null, JSON_INDENT);
    return `${MARKDOWN_HEADER}# Configuration\n\nFile: \`${configPath}\`. Only keys you change are stored; everything else follows the defaults below. Nested keys are written as nested objects:\n\n\`\`\`json\n${example}\n\`\`\`\n\nRebuild and install with \`tools/install.sh\` after editing. Invalid values are ignored, printed as \`settings.invalid\` and the build continues with the default.\n\n${body}`;
}
