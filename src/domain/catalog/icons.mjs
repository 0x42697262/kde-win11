/** @typedef {{ glyph: string, context: string, names: readonly string[], style?: string, tone?: string }} SymbolicIcon */

/**
 * @param {string} glyph
 * @param {string} context
 * @param {readonly string[]} names
 * @param {{ style?: string, tone?: string }} options
 * @returns {SymbolicIcon}
 */
function symbol(glyph, context, names, options = {}) {
    return Object.freeze(Object.assign({ glyph, context, names: Object.freeze(names) }, options));
}

